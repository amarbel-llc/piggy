    #[test]
    fn expand_charset_alnum_is_62_chars() {
        let chars = expand_charset("[:alnum:]");
        assert_eq!(chars.len(), 26 + 26 + 10);
        for c in b'a'..=b'z' {
            assert!(chars.contains(&c));
        }
        for c in b'0'..=b'9' {
            assert!(chars.contains(&c));
        }
    }

    #[test]
    fn expand_charset_punct_alnum_includes_punct() {
        let chars = expand_charset("[:punct:][:alnum:]");
        assert!(chars.contains(&b'!'));
        assert!(chars.contains(&b'@'));
        assert!(chars.contains(&b'~'));
        // alnum still in there
        assert!(chars.contains(&b'a'));
        // space NOT included
        assert!(!chars.contains(&b' '));
        // control bytes not included
        assert!(!chars.contains(&0x01));
    }

    #[test]
    fn expand_charset_literal_bytes_pass_through() {
        let chars = expand_charset("abc[:digit:]");
        assert!(chars.contains(&b'a'));
        assert!(chars.contains(&b'b'));
        assert!(chars.contains(&b'c'));
        assert!(chars.contains(&b'5'));
    }

    #[test]
    fn generate_password_length_matches_alphabet_only() {
        // Drive with an alphabet that includes only the ASCII digits
        // 0..9 — the rejection sampler should still produce a length-N
        // string drawn from those.
        let alphabet: Vec<u8> = (b'0'..=b'9').collect();
        let pass = generate_password(20, &alphabet).unwrap();
        assert_eq!(pass.len(), 20);
        for c in pass.bytes() {
            assert!(c.is_ascii_digit(), "non-digit byte: {c}");
        }
    }

    #[test]
    fn generate_password_with_full_punct_alnum() {
        let alphabet = expand_charset("[:punct:][:alnum:]");
        let pass = generate_password(64, &alphabet).unwrap();
        assert_eq!(pass.len(), 64);
        for c in pass.bytes() {
            assert!(alphabet.contains(&c), "byte {c:#x} not in alphabet");
        }
    }

