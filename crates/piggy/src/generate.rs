//! `piggy pass generate [--no-symbols,-n] [--clip,-c] [--qrcode,-q]
//! [--in-place,-i | --force,-f] pass-name [pass-length]` — native
//! Rust port of `cmd_generate` in `src/piggy.sh` (Split B of #96).
//!
//! Flag rules (mirroring bash + the getopt block):
//!   - `-n` / `--no-symbols` swaps the charset to alnum-only.
//!   - `-q` / `--qrcode` and `-c` / `--clip` are mutually exclusive.
//!   - `-i` / `--in-place` and `-f` / `--force` are mutually exclusive.
//!   - At least one positional (`pass-name`), at most two (`pass-name
//!     pass-length`). Bash's `[[ $# -ne 2 && $# -ne 1 ]]` is exact.
//!
//! Generation strategy: the bash uses `LC_ALL=C tr -dc "$characters"
//! </dev/urandom`, a streaming rejection sampler over a POSIX
//! character class (`[:punct:][:alnum:]` or `[:alnum:]`). We mirror
//! the rejection sampler in pure Rust by precomputing the explicit
//! byte set for the character class and rejecting any non-member
//! byte read from `/dev/urandom`. This preserves the bash's
//! uniform-over-class output distribution (sampling alphabet uniformly
//! across 0..256 and discarding non-members), so a user who set
//! `PIGGY_CHARACTER_SET=[:punct:][:alnum:]` continues to see the
//! same distribution of generated bytes.
//!
//! In-place (`-i`) mode replaces only the first line: the bash
//! pipeline is
//! ```text
//! { echo "$pass"; piggy_decrypt "$passfile" | tail -n +2; } \
//!   | piggy_encrypt "$passfile_temp" "$PIGGY_IDS"
//! mv "$passfile_temp" "$passfile"  # on success
//! ```
//! We mirror by decrypting the prior plaintext, stripping the first
//! line in memory, prepending the new password + `\n`, and encrypting
//! to a sibling temp path that we rename over the live file on
//! success.

use std::io::{Cursor, IsTerminal as _, Read as _, Write as _};
